import type { Core } from '@strapi/strapi';

const allowedMediaTypes = [
  'image/*',
  'video/*',
  'audio/*',
  'application/pdf',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.*',
  'text/plain',
  'text/csv',
];

const deniedTypes = [
  'image/svg+xml',
  'application/vnd.microsoft.portable-executable',
  'application/x-msdownload',
  'application/x-msdos-program',
  'application/x-executable',
  'application/x-dosexec',
  'application/x-sh',
  'text/x-shellscript',
  'application/x-mach-binary',
];

const config = ({ env }: Core.Config.Shared.ConfigParams): Core.Config.Plugin => ({
  'users-permissions': {
    config: {
      // The Next.js server keeps this JWT in its own httpOnly cookie and forwards it as a
      // Bearer token, so a single bounded-lifetime token is simpler than refresh rotation.
      jwtManagement: 'legacy-support',
      jwt: { expiresIn: env('JWT_EXPIRES_IN', '7d') },
      // Sign-up only accepts username, e-mail and password: roles and profile fields are never client-settable.
      register: { allowedFields: [] },
    },
  },
  upload: {
    config: {
      security: {
        allowedTypes: allowedMediaTypes,
        deniedTypes,
      },
    },
  },
});

export default config;
